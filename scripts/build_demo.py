"""Rebuild the whole SYNTHETIC demo from scratch: population, models, Rahim and the abstention applicant.

Outputs: data/synthetic/* (deterministic population, splits, data card, metrics) and
private_data/demo/* (demo SQLite ledger, model artefacts, backend.env, manifest). The previous
private_data/demo directory is removed only if it carries this script's build marker; existing
databases such as private_data/agrogami.db and earlier synthetic_demo scenarios are never touched.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agrogami.application import ApplicationService, EvaluationRun  # noqa: E402
from agrogami.calibration.core import Calibrator, validate_evaluation  # noqa: E402
from agrogami.risk.loading import load_risk_components  # noqa: E402
from agrogami.risk.models import LogisticRiskModel, TreeRiskModel, ValidationScope  # noqa: E402
from agrogami.schemas import utcnow  # noqa: E402
from agrogami.storage import Store  # noqa: E402
from agrogami.synthetic import population as P  # noqa: E402
from agrogami.synthetic.identities import ABSTENTION_APPLICANT_ID, RAHIM_APPLICANT_ID  # noqa: E402
from agrogami.synthetic.ledger import next_assessment_time  # noqa: E402
from agrogami.synthetic.pipeline import (ALGORITHMS, REPORT_CAVEAT, generate, load_splits, metrics_table,  # noqa: E402
                                         train_all, write_population)
from agrogami.synthetic.rahim import build_rahim, summarize  # noqa: E402
from scripts.prepare_demo import abstention_scenario  # noqa: E402
from scripts.train_synthetic_risk import add_model_arguments, hyperparameters  # noqa: E402

DATA_DIR = ROOT / "data" / "synthetic"
DEMO_DIR = ROOT / "private_data" / "demo"
MARKER = ".agrogami-demo-build"


def fresh_demo_dir(directory: Path) -> None:
    if directory.exists():
        if not (directory / MARKER).is_file():
            raise SystemExit(f"{directory.name} exists without the build marker; refusing to delete it")
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    (directory / MARKER).write_text("Generated by scripts/build_demo.py; safe to delete and rebuild.\n", encoding="utf-8")


def relative(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def content_digest(summary: dict) -> str:
    """Hash of run-invariant outputs: data files plus Rahim's model outputs and features."""
    digest = hashlib.sha256()
    for path in sorted(DATA_DIR.iterdir()):
        digest.update(path.name.encode() + b"\0" + path.read_bytes())
    stable = {k: v for k, v in summary.items() if k not in {"assessment_id", "assessment_time"}}
    digest.update(json.dumps(stable, sort_keys=True, default=str).encode())
    return digest.hexdigest()


def persist_evaluations(service: ApplicationService, models_dir: Path, report: dict) -> dict[str, str]:
    _, _, test = load_splits(DATA_DIR)
    runs = {}
    for algorithm in ALGORITHMS:
        target = models_dir / algorithm
        model = LogisticRiskModel.load(target / "model.json") if algorithm == "logistic" else TreeRiskModel.load(target / "tree")
        calibrator = Calibrator.load(target / "calibrator.json")
        lineage = validate_evaluation(test, model.artifact, calibrator.artifact)
        result = report["models"][algorithm]
        run = EvaluationRun(dataset_id=test.identity.dataset_id, scope=ValidationScope.SYNTHETIC_DEMO,
            metrics={f"{stage}_{metric}": result[stage][metric] for stage in ("raw", "calibrated")
                     for metric in ("auc", "brier", "log_loss")},
            private_lineage=lineage, limitations=(f"Synthetic recovery test ({algorithm})", REPORT_CAVEAT))
        service.records.save(run)
        runs[algorithm] = str(run.run_id)
    return runs


def main(argv: list[str] | None = None) -> dict:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=P.DEFAULT_SEED)
    parser.add_argument("--n", type=int, default=P.DEFAULT_N)
    parser.add_argument("--workers", type=int, default=None)
    add_model_arguments(parser)
    args = parser.parse_args(argv)
    t0 = next_assessment_time()
    fresh_demo_dir(DEMO_DIR)
    print(f"[1/4] Generating {args.n} SYNTHETIC borrowers (seed {args.seed})...", flush=True)
    records = generate(args.seed, args.n, t0, workers=args.workers)
    for stale in ("metrics.json",):
        (DATA_DIR / stale).unlink(missing_ok=True)
    population = write_population(records, DATA_DIR, seed=args.seed, n=args.n)
    print(f"      default rate {population['default_rate']:.2%}; bridge rows {population['bridge']['rows']}, "
          f"excluded {population['bridge']['excluded']}", flush=True)
    print("[2/4] Training and calibrating LR / LightGBM / XGBoost...", flush=True)
    models_dir = DEMO_DIR / "models"
    report = train_all(DATA_DIR, models_dir, seed=args.seed, hyperparameters=hyperparameters(args), lr_c=args.lr_c,
                       primary=args.primary, method=args.method, population=records)
    (DATA_DIR / "metrics.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    selected = models_dir / args.primary
    paths = {"AGROGAMI_DATABASE_URL": "sqlite:///" + relative(DEMO_DIR / "agrogami-demo.db"),
             "AGROGAMI_PRIVATE_DATA_DIR": relative(DEMO_DIR / "private"),
             "AGROGAMI_RISK_MODEL_PATH": relative(selected / "tree"),
             "AGROGAMI_CALIBRATOR_PATH": relative(selected / "calibrator.json"),
             "AGROGAMI_SHAP_BACKGROUND_PATH": relative(selected / "shap_background.json")}
    print("[3/4] Building the demo ledger (abstention applicant + Rahim)...", flush=True)
    model, calibrator, explainer = load_risk_components(selected / "tree", selected / "calibrator.json",
                                                        selected / "shap_background.json")
    store = Store("sqlite:///" + (DEMO_DIR / "agrogami-demo.db").as_posix())
    try:
        service = ApplicationService(store, DEMO_DIR / "private", model=model, calibrator=calibrator,
                                     explanation_provider=explainer)
        abstention = abstention_scenario(service, ABSTENTION_APPLICANT_ID, utcnow())
        rahim = build_rahim(service, t0)
        evaluations = persist_evaluations(service, models_dir, report)
    finally:
        store.engine.dispose()
    summary = summarize(rahim["assessment"], rahim["snapshots"])
    (DEMO_DIR / "backend.env").write_text("".join(f"{k}={v}\n" for k, v in paths.items()), encoding="utf-8")
    manifest = {"scope": "SYNTHETIC_DEMO", "assessment_time_t0": t0.isoformat(),
                "rahim": {"applicant_id": str(RAHIM_APPLICANT_ID), "sms_count": rahim["sms_count"],
                          "edge_case_event_ids": rahim["edge_case_event_ids"], "assessment": summary},
                "abstention": abstention, "evaluation_run_ids": evaluations,
                "selected_checkpoint": args.primary, "content_digest": content_digest(summary)}
    (DEMO_DIR / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print("[4/4] Done.\n")
    print(metrics_table(report))
    print("\nRahim's stored assessment:")
    print(json.dumps(summary, indent=2))
    print(f"\nAbstention applicant {abstention['applicant_id']}: {abstention['assessment_status']}")
    print(f"Backend settings written to {relative(DEMO_DIR / 'backend.env')}; serve them with .\\scripts\\run_demo_api.ps1.")
    print(f"Content digest (identical across reruns): {manifest['content_digest']}")
    print(f"\nRahim applicant UUID: {RAHIM_APPLICANT_ID}")
    return manifest


if __name__ == "__main__":
    main()
